const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
function load(file, varName) {
  const code = fs.readFileSync(path.join(ROOT, file), "utf8");
  return Function(`return (${code.replace(`window.${varName} = `, "").replace(/;\s*$/, "")})`)();
}
function save(file, varName, data) {
  fs.writeFileSync(path.join(ROOT, file), `window.${varName} = ${JSON.stringify(data, null, 2)};\n`, "utf8");
}

function stripJunk(html) {
  if (!html) return html;
  return html.replace(/<p>([^<]*)<\/p>/g, (full, inner) => {
    if (
      /비교 번호는|메모에서 흔들린 적이|기록 \d+에서 문제가|번째 비교를 남겼|배합은 그대로입니다/.test(
        inner
      )
    )
      return "";
    if (/가 [a-z0-9-]+ 메모에서|가 [a-z0-9-]+ 기록/.test(inner)) return "";
    return full;
  });
}

